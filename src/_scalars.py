import json
from utils import camel_to_snake

schema = json.load(open("./schema.json"))

types = schema["data"]["__schema"]["types"]

scalars = [t for t in types if t["kind"] == "SCALAR"]

"""
Scalar class template

class CustomScalarType(String):
    pass
"""
def generate_scalar_class(scalar_data: dict):
    class_code = f"""
\"\"\"
This is autogenerated code. Do not edit directly.
\"\"\"    
from schema.scalars.string import String

class {scalar_data["name"]}(String):
    pass
"""
    return class_code

for s in scalars:
    if s["name"] in ("Int", "Float", "Boolean", "ID", "String"):
        continue
    class_code = generate_scalar_class(s)
    with open(f"./schema/scalars/{camel_to_snake(s['name'])}.py", "w") as f:
        f.write(class_code)