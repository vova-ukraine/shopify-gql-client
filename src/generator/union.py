from generator.object import ObjectGenerator

# TODO: Review generators inheriting from ObjectGenerator
class UnionGenerator(ObjectGenerator):
    kind_name = "UNION"
    kind_dir_name = "unions"

    def _generate_class_code(self, type_data: dict):
        possible_types = []
        import_type_loaders = set()
        for possible_type in type_data["possibleTypes"]:
            possible_type_kind, possible_type_name, _ = self._get_field_kind_and_type(possible_type)
            possible_type_name = self._normalize_identifier(possible_type_name)
            type_loader_name = possible_type_kind.capitalize() + "TypeLoader"
            import_type_loaders.add(type_loader_name)
            possible_types.append(f"\"{possible_type_name}\": {type_loader_name}")
        possible_types_block = ",\n        ".join(sorted(possible_types))
        class_code = f"""\"\"\"
This is autogenerated code. Do not edit directly.
\"\"\"
from base_types import UnionType
from type_loaders import {", ".join(sorted(import_type_loaders))}


class {type_data["name"]}(UnionType):
    possible_type_loaders = {{
        {possible_types_block}
    }}
"""
        return class_code