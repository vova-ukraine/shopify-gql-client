import os
from generator.base import BaseGenerator

class ScalarGenerator(BaseGenerator):
    kind_name = "SCALAR"
    kind_dir_name = "scalars"

    buildin_type_files = {
        "Int": "int.py",
        "Float": "float.py",
        "Boolean": "boolean.py",
        "ID": "id.py",
        "String": "string.py",
    }

    def _generate_class_code(self, type_data: dict):
        if type_data["name"] in self.buildin_type_files:
            return self._load_buildin_type(type_data["name"])
        class_code = f"""\"\"\"
This is autogenerated code. Do not edit directly.
\"\"\"    
from schema.scalars.string import String

class {type_data["name"]}(String):
    pass
"""
        return class_code
    
    def _load_buildin_type(self, type_name: str):
        current_file_directory = os.path.dirname(os.path.abspath(__file__))
        with open(f"{current_file_directory}/buildin_types/{self.buildin_type_files[type_name]}", "r") as f:
            return f.read()