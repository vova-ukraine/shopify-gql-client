import json
from utils import camel_to_snake

schema = json.load(open("./schema.json"))

types = schema["data"]["__schema"]["types"]

enums = [t for t in types if t["kind"] == "ENUM"]

#print object names in new lines
#print("\n".join([o["name"] for o in enums]))

#enums = enums[:1]

"""
Enum class template

class CustomEnumType(EnumType):
    ENUM_VALUE = "ENUM_VALUE"
"""
def generate_enum_class(enum_data: dict):
    values_block = ""
    for enum_value in enum_data["enumValues"]:
        values_block += f"    {enum_value['name']} = \"{enum_value['name']}\"\n"
    class_code = f"""
\"\"\"
This is autogenerated code. Do not edit directly.
\"\"\"    
from classes import EnumType

class {enum_data["name"]}(EnumType):
{values_block}
    """
    return class_code

for e in enums:
    class_code = generate_enum_class(e)
    with open(f"./schema/enums/{camel_to_snake(e['name'])}.py", "w") as f:
        f.write(class_code)

